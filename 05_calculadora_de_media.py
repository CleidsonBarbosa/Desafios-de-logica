'''Desenvolva um sistema que solicite três números inteiros, calcule e exiba a média dentre estes números.'''
x = int(input('digite o valor do primeiro número interiro: '))
y = int(input('digite o valor do segundo número interiro: '))
z = int(input('digite o valor do terceiro número interiro: '))
soma = x + y + z
print(f'O valor da soma dos 3 números é', soma)